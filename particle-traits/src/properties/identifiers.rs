//!
//! Provides identifier property traits.
//!
//! [`Identifier`] types are used unique identifiers for objects.
//!

use crate::strings::{AsStr, CheckedFromStr, LengthLimitedTextProperty};
use core::{fmt::Display, iter};

// ------------------------------------------------------------------------------------------------
// Public Types ❱ Identifier
// ------------------------------------------------------------------------------------------------

/// 
/// Provides a trait for identifier types.
/// 
pub trait Identifier:
    Clone + Display + Eq + AsStr + CheckedFromStr + LengthLimitedTextProperty
{
}

// ------------------------------------------------------------------------------------------------
// Public Types ❱ Identifier Generators
// ------------------------------------------------------------------------------------------------

/// 
/// Provides a trait for types that can generate unique identifiers.
/// 
pub trait IdGenerator {
    /// The identifier implementation to be generated by this object.
    type Identifier: Identifier;

    fn generate(&self) -> Self::Identifier;
}

// ------------------------------------------------------------------------------------------------
// Public Types ❱ Has Identifier traits
// ------------------------------------------------------------------------------------------------

/// 
/// Provides a trait for types that have an associated unique identifier.
/// 
pub trait HasIdentifier {
    /// The identifier implementation to be included in the built object.
    type Identifier: Identifier;

    /* const */
    fn identifier(&self) -> &Self::Identifier;
}

/// 
/// Provides a trait for types that have a mutable associated unique identifier.
/// 
pub trait HasIdentifierMut: HasIdentifier {
    /* const */
    fn set_identifier(&mut self, identifier: Self::Identifier);
}

// ------------------------------------------------------------------------------------------------
// Public Types ❱ Has Parent Identifier traits
// ------------------------------------------------------------------------------------------------

/// 
/// Provides a trait for types that have an associated parent unique identifier.
/// 
pub trait HasParentIdentifier: HasIdentifier {
    /* const */
    fn has_parent_identifier(&self) -> bool;

    /* const */
    fn parent_identifier(&self) -> Option<&Self::Identifier>;
}

/// 
/// Provides a trait for types that have a mutable associated parent unique identifier.
/// 
pub trait HasParentIdentifierMut: HasParentIdentifier {
    fn set_parent_identifier(&mut self, parent_identifier: Self::Identifier);

    fn unset_parent_identifier(&mut self);
}

// ------------------------------------------------------------------------------------------------
// Public Types ❱ Has Child Identifier traits
// ------------------------------------------------------------------------------------------------

/// 
/// Provides a trait for types that have associated child unique identifiers.
/// 
pub trait HasChildIdentifiers: HasIdentifier {
    /* const */
    fn child_identifier_count(&self) -> usize;

    /* const */
    fn has_child_identifiers(&self) -> bool;

    fn child_identifiers(&self) -> impl Iterator<Item = &Self::Identifier>;
}

/// 
/// Provides a trait for types that have mutable associated child unique identifiers.
/// 
pub trait HasChildIdentifiersMut: HasChildIdentifiers {
    fn child_identifiers_mut(&mut self) -> impl Iterator<Item = &mut Self::Identifier>;

    fn add_child_identifier(&mut self, child_identifier: Self::Identifier);

    fn extend_child_identifiers<I: IntoIterator<Item = Self::Identifier>>(
        &mut self,
        child_identifiers: I,
    );

    fn remove_child_identifier(&mut self, child_identifier: &Self::Identifier);

    fn clear_child_identifiers(&mut self);
}

// ------------------------------------------------------------------------------------------------
// Public Types ❱ Builder Fragments
// ------------------------------------------------------------------------------------------------

///
/// Provides a builder mix-in fragment for types that can have identifiers.
/// 
pub trait IdentifierBuilderFragment {
    /// The identifier implementation to be included in the built object.
    type Identifier: Identifier;

    fn with_identifier(self, identifier: Self::Identifier) -> Self;
}

///
/// Provides a builder mix-in fragment for types that can have parent identifiers.
/// 
pub trait ParentIdentifierBuilderFragment {
    /// The parent identifier implementation to be included in the built object.
    type Identifier: Identifier;

    fn with_parent_identifier(self, parent_identifier: Self::Identifier) -> Self;

    fn with_parent<P: HasIdentifier<Identifier = Self::Identifier>>(self, parent: &P) -> Self
    where
        Self: Sized,
    {
        self.with_parent_identifier(parent.identifier().clone())
    }
}

/// 
/// Provides a builder mix-in fragment for types that can have child identifiers.
/// 
pub trait ChildIdentifiersBuilderFragment {
    /// The child identifier implementation to be included in the built object.
    type Identifier: Identifier;

    fn with_child_identifiers<I: IntoIterator<Item = Self::Identifier>>(
        self,
        child_identifiers: I,
    ) -> Self;

    fn with_child<I: HasIdentifier<Identifier = Self::Identifier>>(self, child: &I) -> Self
    where
        Self: Sized,
    {
        self.with_child_identifiers(iter::once(child.identifier().clone()))
    }

    fn with_children<C: HasIdentifier<Identifier = Self::Identifier>, I: IntoIterator<Item = C>>(
        self,
        children: I,
    ) -> Self
    where
        Self: Sized,
    {
        self.with_child_identifiers(children.into_iter().map(|c| c.identifier().clone()))
    }
}
